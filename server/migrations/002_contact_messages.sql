-- Messages sent through the contact form. They are kept here so staff can read them in the console
-- whether or not an email provider is configured; when email is on, it is only a notification.
create table contact_messages (
  id integer generated by default as identity primary key,
  name text not null,
  email text not null,
  topic text not null,
  message text not null,
  handled boolean not null default false,
  handled_by integer references users(id) on delete set null,
  handled_at timestamptz,
  created_at timestamptz not null default now()
);
create index contact_messages_handled_idx on contact_messages(handled, id);
alter table contact_messages enable row level security;
